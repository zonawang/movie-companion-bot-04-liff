import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdir } from 'node:fs/promises';
const server = spawn(process.execPath, ['scripts/preview.mjs'], { env: { ...process.env, PREVIEW_PORT: '3104' }, stdio: ['ignore','pipe','inherit'] });
await new Promise((resolve, reject) => { server.stdout.once('data', resolve); server.once('error', reject); server.once('exit', code => reject(new Error('Preview exited: ' + code))); });
await mkdir('browser-results', { recursive: true });
(async () => {
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1100}});
 const errors=[]; page.on('pageerror', e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:3104/tickets/?preview=1');
 await page.locator('.ticket').first().waitFor();
 assert.equal(await page.locator('.ticket').count(),6);
 await page.screenshot({path:'browser-results/ticket-shelf-desktop.png',fullPage:true});
 await page.locator('#query').fill('雨停'); await page.waitForTimeout(350); assert.equal(await page.locator('.ticket').count(),1);
 await page.locator('.ticket').click(); assert.equal(await page.locator('#detail-title').innerText(),'雨停之前');
 await page.locator('#edit').click(); await page.locator('#note').fill('原樣保留\n<script>window.HACKED=1</script>'); await page.locator('#save').click();
 await page.locator('#editor').waitFor({state:'hidden'}); await page.locator('.ticket').click();
 assert.equal(await page.locator('.detail-note').innerText(),'原樣保留\n<script>window.HACKED=1</script>');
 assert.equal(await page.evaluate(()=>window.HACKED),undefined);
 await page.locator('#delete').click(); await page.locator('#confirm-delete').click(); await page.locator('#delete-dialog').waitFor({state:'hidden'});
 await page.locator('#empty').waitFor();
 await page.locator('#query').fill(''); await page.waitForTimeout(350);
 await page.locator('#add').click(); await page.locator('#movie-title').fill('新電影'); await page.locator('#note').fill('新心得'); await page.locator('#save').click(); await page.locator('#editor').waitFor({state:'hidden'});
 assert.equal(await page.locator('.ticket').count(),6);
 await page.locator('#year').selectOption('2025'); await page.waitForFunction(() => document.querySelectorAll('.ticket').length === 2); assert.equal(await page.locator('.ticket').count(),2);
 await page.locator('#year').selectOption('');
 await page.setViewportSize({width:390,height:844}); await page.screenshot({path:'browser-results/ticket-shelf-mobile.png',fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
 await page.locator('#add').click(); assert.equal(await page.locator('#editor').isVisible(),true);
 await page.screenshot({path:'browser-results/mobile-form.png',fullPage:true});
 assert.equal(await page.evaluate(()=>document.querySelector('#editor').scrollWidth<=document.querySelector('#editor').clientWidth),true);
 await page.goto('http://127.0.0.1:3104/tickets/'); await page.locator('#line-link').waitFor();
 assert.match(await page.locator('#gate-message').innerText(),/我的票匣/);
 assert.deepEqual(errors,[]); console.log('Browser QA passed: desktop/mobile, filters, add/edit/delete, verbatim note, XSS, unauthenticated gate, no overflow.'); await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1}).finally(()=>server.kill('SIGTERM'));
